namespace YMM4EffectShapes.Solid3D;

/// <summary>2D版の図形をもとに、3Dで描く版の図形を作る</summary>
public abstract class Solid3DPlugin<T> : IShapePlugin where T : IShapePlugin, new()
{
    static readonly T inner = new();
    public string Name => Solid3DDefaults.Name3D(inner.Name);
    public bool IsExoShapeSupported => false;
    public bool IsExoMaskSupported => false;
    public IShapeParameter CreateShapeParameter(SharedDataStore? sharedData)
    {
        var p = inner.CreateShapeParameter(sharedData);
        if (p is EffectShapeParameterBase e) Solid3DDefaults.Apply(e, inner.Name, typeof(T).Name);
        return p;
    }
}

/// <summary>3D版の名前と初期値</summary>
public static class Solid3DDefaults
{
    public const string Prefix2D = "演出：", Prefix3D = "演出3D：";
    public const string Namespace3D = "YMM4EffectShapes.Solid3D.";

    public static string Name3D(string name2D) => name2D.StartsWith(Prefix2D, StringComparison.Ordinal) ? Prefix3D + name2D[Prefix2D.Length..] : Prefix3D + name2D;

    /// <summary>2D版の型名 → 3D版の型名</summary>
    public static string Key3D(string key2D) => key2D.StartsWith("YMM4EffectShapes.", StringComparison.Ordinal) && !key2D.StartsWith(Namespace3D, StringComparison.Ordinal)
        ? Namespace3D + key2D["YMM4EffectShapes.".Length..] : key2D;

    public static bool Is3DKey(string key) => key.StartsWith(Namespace3D, StringComparison.Ordinal);

    /// <summary>3D版の型名 → 2D版の型名</summary>
    public static string Key2D(string key) => Is3DKey(key) ? "YMM4EffectShapes." + key[Namespace3D.Length..] : key;

    // 降る・舞う・漂う物(部品を奥の方にも散らばらせる)。型の名前で決める
    static readonly HashSet<string> Particles =
    [
        "RainPlugin", "SnowPlugin", "SnowflakePlugin", "BlizzardPlugin", "CloudPlugin", "FogPlugin", "WindPlugin", "SandstormPlugin",
        "StarsPlugin", "MeteorShowerPlugin", "AuroraPlugin", "SmokePlugin", "SakuraPlugin", "FallingLeavesPlugin", "FlyersPlugin",
        "FirefliesPlugin", "BubblePlugin", "SparklePlugin", "FireworksPlugin", "FeathersPlugin", "ConfettiPlugin", "BokehPlugin",
        "FishSchoolPlugin", "SkyLanternsPlugin", "MoneyRainPlugin", "HeartsRisePlugin", "CommentFlowPlugin", "DustPlugin",
        "DigitalRainPlugin", "DataStreamPlugin", "WarpPlugin",
    ];
    // その場でひらひら回る物
    static readonly HashSet<string> Tumbles = ["SakuraPlugin", "FallingLeavesPlugin", "FeathersPlugin", "ConfettiPlugin", "MoneyRainPlugin", "SnowflakePlugin"];
    // ゆっくり前後に漂う物
    static readonly HashSet<string> Drifts = ["FirefliesPlugin", "BubblePlugin", "BokehPlugin", "SkyLanternsPlugin", "FishSchoolPlugin", "AuroraPlugin", "DustPlugin"];
    // 板を奥に並べる方がきれいな物(厚みを付けると棒のように見える)
    static readonly HashSet<string> Flats = ["AuroraPlugin", "CloudPlugin", "FogPlugin", "SmokePlugin", "BokehPlugin", "SandstormPlugin"];    // 画面いっぱいの背景(大きく回すと端が見えるので、少しだけ傾ける)
    static readonly string[] Backgrounds = ["背景", "空", "夜景", "壁", "部屋", "グラデ", "模様", "和柄", "地面", "海", "森", "街", "教室", "ステージ", "画面"];

    /// <param name="typeName">2D版の型の名前(降る物かどうかを決める)</param>
    public static void Apply(EffectShapeParameterBase p, string name2D, string typeName = "")
    {
        var n = name2D.StartsWith(Prefix2D, StringComparison.Ordinal) ? name2D[Prefix2D.Length..] : name2D;
        if (n.Contains("文字PV背景"))
        {
            p.Apply3DDefaults(0, 0, 0, 0);
            return;
        }
        if (Particles.Contains(typeName))
        {
            p.Apply3DDefaults(1500, 0, 0, 0);
            if (Flats.Contains(typeName)) p.DepthMode = Depth3DMode.Flat;
            if (Tumbles.Contains(typeName)) p.PartSpin3D.Values[0].Value = 160;
            if (Drifts.Contains(typeName)) { p.PartWave3D.Values[0].Value = 120; p.PartWaveSpeed3D.Values[0].Value = 0.3; }
        }
        else if (Backgrounds.Any(n.Contains))
        {
            p.Apply3DDefaults(0, -6, 10, 0);
            p.Depth3D.Values[0].Value = 20;
        }
        else p.Apply3DDefaults(0, -12, 22, 0);
    }
}

